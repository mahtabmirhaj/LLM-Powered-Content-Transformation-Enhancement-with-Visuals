"""

Markdown Output Comparison System - Azure OpenAI Version



This script evaluates and compares markdown files generated by different PDF extraction systems

against the original PDF content to determine which system performs better.



Required dependencies:

- openai

- pdfminer.six or PyMuPDF

- numpy

- matplotlib

- tqdm

- python-dotenv

"""



import os

import json

import time

import numpy as np

import matplotlib.pyplot as plt

from tqdm import tqdm

from datetime import datetime

import re

from typing import List, Dict, Any, Tuple

from dotenv import load_dotenv



# Load environment variables from .env file

load_dotenv()



# Import OpenAI

import openai



# Check for required Azure OpenAI environment variables

required_vars = ["AZURE_OPENAI_API_KEY", "API_VERSION", "DEPLOYMENT_NAME", "ENDPOINT_URL"]

missing_vars = [var for var in required_vars if not os.getenv(var)]

if missing_vars:

    print(f"Error: Missing required environment variables: {', '.join(missing_vars)}")

    print("Please create a .env file with these variables.")

    exit(1)



# Try to import PDF processing libraries

try:

    import fitz  # PyMuPDF

except ImportError:

    print("Warning: PyMuPDF not installed. Using pdfminer.six as fallback.")

    try:

        from pdfminer.high_level import extract_text as pdfminer_extract_text

    except ImportError:

        print("Error: Neither PyMuPDF nor pdfminer.six is installed.")

        print("Please install at least one: pip install pymupdf OR pip install pdfminer.six")

        exit(1)





class MarkdownComparisonEvaluator:

    """Class for comparing markdown outputs from different PDF extraction systems."""

   

    def __init__(self, verbose=True):

        """

        Initialize the evaluator.

       

        Args:

            verbose: Whether to print detailed progress information

        """

        self.deployment_name = os.getenv("DEPLOYMENT_NAME")

        self.verbose = verbose

        self.results_dir = f"comparison_results_{datetime.now().strftime('%Y%m%d_%H%M%S')}"

        os.makedirs(self.results_dir, exist_ok=True)

       

        # Initialize Azure OpenAI client

        self.client = openai.AzureOpenAI(

            api_key=os.getenv("AZURE_OPENAI_API_KEY"),

            api_version=os.getenv("API_VERSION"),

            azure_endpoint=os.getenv("ENDPOINT_URL")

        )

   

    def log(self, message):

        """Print log messages if verbose mode is enabled."""

        if self.verbose:

            print(message)

   

    def extract_pdf_text(self, pdf_path):

        """

        Extract text from a PDF file.

       

        Args:

            pdf_path: Path to the PDF file

           

        Returns:

            Extracted text content

        """

        try:

            # Try PyMuPDF first if available

            if 'fitz' in globals():

                doc = fitz.open(pdf_path)

                text = ""

                for page in doc:

                    text += page.get_text()

                doc.close()

                return text

            else:

                # Fall back to pdfminer.six

                return pdfminer_extract_text(pdf_path)

        except Exception as e:

            self.log(f"Error extracting text from PDF {pdf_path}: {e}")

            return ""

   

    def read_markdown_file(self, md_path):

        """

        Read content from a markdown file.

       

        Args:

            md_path: Path to the markdown file

           

        Returns:

            Content of the markdown file

        """

        try:

            with open(md_path, 'r', encoding='utf-8') as file:

                return file.read()

        except Exception as e:

            self.log(f"Error reading markdown file {md_path}: {e}")

            return ""

   

    def query_azure_openai(self, prompt, system_prompt=None, json_output=False):

        """

        Query Azure OpenAI with a prompt.

       

        Args:

            prompt: The user prompt to send to the LLM

            system_prompt: Optional system prompt for setting the LLM's behavior

            json_output: Whether to request JSON output from the LLM

       

        Returns:

            The LLM's response text

        """

        messages = []

       

        if system_prompt:

            messages.append({"role": "system", "content": system_prompt})

           

        messages.append({"role": "user", "content": prompt})

       

        response_format = {"type": "json_object"} if json_output else None

       

        try:

            response = self.client.chat.completions.create(

                model=self.deployment_name,

                messages=messages,

                response_format=response_format,

                temperature=0.2  # Lower temperature for more consistent evaluations

            )

            return response.choices[0].message.content

        except Exception as e:

            self.log(f"Error querying Azure OpenAI: {e}")

            raise

   

    def evaluate_content_preservation(self, md_content, pdf_content, system_name):

        """

        Evaluate how well the markdown content preserves the original PDF content.

       

        Args:

            md_content: Content of the markdown file

            pdf_content: Content of the original PDF

            system_name: Name of the extraction system

           

        Returns:

            Dictionary with evaluation results

        """

        # Prepare content for comparison (limit length to avoid token limits)

        max_content_length = 6000

        md_sample = md_content[:max_content_length]

        pdf_sample = pdf_content[:max_content_length]

       

        prompt = f"""

        Compare the following markdown text generated by the {system_name} extraction system with the original PDF content.

       

        ORIGINAL PDF CONTENT:

        {pdf_sample}

       

        MARKDOWN OUTPUT FROM {system_name.upper()}:

        {md_sample}

       

        Evaluate the content preservation on a scale of 0-100, where 100 means perfect preservation.

        Consider the following aspects:

       

        1. Text content: Is all the important text from the PDF preserved in the markdown?

        2. Structural elements: Are headings, paragraphs, lists, etc. properly preserved?

        3. Formatting: Is important formatting (bold, italic, etc.) preserved where relevant?

        4. Image references: Are references to images preserved (not the images themselves)?

        5. Table content: Is table data preserved and structured properly?

       

        Return your evaluation as a JSON object with the following fields:

        - overall_score: A number from 0-100 representing overall content preservation

        - text_score: Score for text content preservation (0-100)

        - structure_score: Score for structural elements preservation (0-100)

        - formatting_score: Score for formatting preservation (0-100)

        - image_references_score: Score for image references preservation (0-100)

        - table_content_score: Score for table content preservation (0-100)

        - strengths: List of strengths in the extraction

        - weaknesses: List of weaknesses in the extraction

        - missing_elements: List of important elements missing in the markdown

        - additional_notes: Any other observations

        """

       

        try:

            evaluation_json = self.query_azure_openai(prompt, json_output=True)

            evaluation = json.loads(evaluation_json)

            self.log(f"{system_name} evaluation - Overall score: {evaluation.get('overall_score', 'N/A')}")

            return evaluation

        except Exception as e:

            self.log(f"Error during evaluation for {system_name}: {e}")

            return {

                "overall_score": 0,

                "text_score": 0,

                "structure_score": 0,

                "formatting_score": 0,

                "image_references_score": 0,

                "table_content_score": 0,

                "strengths": [],

                "weaknesses": ["Evaluation failed with error: " + str(e)],

                "missing_elements": ["Unknown due to evaluation failure"],

                "additional_notes": f"Error during evaluation: {e}"

            }

   

    def analyze_markdown_structure(self, md_content, system_name):

        """

        Analyze the structure of the markdown content.

       

        Args:

            md_content: Content of the markdown file

            system_name: Name of the extraction system

           

        Returns:

            Dictionary with structural analysis results

        """

        # Simple structural analysis without LLM

        analysis = {

            "headings": {

                "h1": len(re.findall(r'^# .+', md_content, re.MULTILINE)),

                "h2": len(re.findall(r'^## .+', md_content, re.MULTILINE)),

                "h3": len(re.findall(r'^### .+', md_content, re.MULTILINE)),

                "h4_plus": len(re.findall(r'^#{4,} .+', md_content, re.MULTILINE))

            },

            "paragraphs": len(re.findall(r'\n\n(?!\#|\*|\d+\.|\>)', md_content)),

            "lists": {

                "unordered": len(re.findall(r'^\* .+', md_content, re.MULTILINE)),

                "ordered": len(re.findall(r'^\d+\. .+', md_content, re.MULTILINE))

            },

            "code_blocks": len(re.findall(r'```.*?\n.*?```', md_content, re.DOTALL)),

            "tables": len(re.findall(r'\|.*\|.*\n\|[-\s\|:]+\|', md_content)),

            "images": len(re.findall(r'!\[.*?\]\(.*?\)', md_content)),

            "links": len(re.findall(r'\[.*?\]\(.*?\)', md_content)),

            "blockquotes": len(re.findall(r'^> .+', md_content, re.MULTILINE)),

            "horizontal_rules": len(re.findall(r'^---+$', md_content, re.MULTILINE)),

            "total_chars": len(md_content),

            "total_words": len(md_content.split())

        }

       

        # Use LLM for deeper structural analysis

        prompt = f"""

        Analyze the structure of this markdown document generated by the {system_name} extraction system.

       

        MARKDOWN CONTENT SAMPLE:

        {md_content[:5000] if len(md_content) > 5000 else md_content}

       

        Based on this sample, evaluate the structural quality of the markdown on a scale of 0-100,

        where 100 represents perfectly structured markdown that follows best practices.

       

        Consider:

        1. Proper heading hierarchy (H1 -> H2 -> H3, no skipping levels)

        2. Consistent formatting of similar elements

        3. Appropriate use of markdown features (lists, code blocks, etc.)

        4. Overall document organization

       

        Return your evaluation as a JSON object with:

        - structure_quality_score: A number from 0-100

        - hierarchy_consistency: Score for heading hierarchy consistency (0-100)

        - formatting_consistency: Score for consistent formatting (0-100)

        - markdown_usage: Score for appropriate use of markdown features (0-100)

        - organization_quality: Score for overall document organization (0-100)

        - strengths: List of structural strengths

        - issues: List of structural issues or inconsistencies

        - recommendations: Suggestions for structural improvements

        """

       

        try:

            evaluation_json = self.query_azure_openai(prompt, json_output=True)

            llm_analysis = json.loads(evaluation_json)

           

            # Combine automated and LLM analysis

            analysis.update({

                "structure_quality_score": llm_analysis.get("structure_quality_score", 0),

                "hierarchy_consistency": llm_analysis.get("hierarchy_consistency", 0),

                "formatting_consistency": llm_analysis.get("formatting_consistency", 0),

                "markdown_usage": llm_analysis.get("markdown_usage", 0),

                "organization_quality": llm_analysis.get("organization_quality", 0),

                "strengths": llm_analysis.get("strengths", []),

                "issues": llm_analysis.get("issues", []),

                "recommendations": llm_analysis.get("recommendations", [])

            })

           

            self.log(f"{system_name} structure analysis - Quality score: {analysis.get('structure_quality_score', 'N/A')}")

            return analysis

        except Exception as e:

            self.log(f"Error during structure analysis for {system_name}: {e}")

            # Return just the automated analysis on error

            return analysis

   

    def compare_systems(self, evaluations):

        """

        Generate a comparative analysis of different extraction systems.

       

        Args:

            evaluations: Dictionary mapping system names to their evaluation results

           

        Returns:

            Comparative analysis text

        """

        # Format the evaluations for LLM consumption

        formatted_evaluations = json.dumps(evaluations, indent=2)

       

        prompt = f"""

        Compare the following PDF-to-markdown extraction systems based on their evaluation results:

       

        {formatted_evaluations}

       

        Provide a detailed academic comparison focusing on:

       

        1. Overall Performance: Which system performs better overall and why?

        2. Content Preservation: Compare how well each system preserves the original PDF content.

        3. Structural Quality: Compare the structural quality of the markdown output.

        4. Strengths and Weaknesses: Highlight the unique strengths and weaknesses of each system.

        5. Optimal Use Cases: Identify the types of documents or scenarios where each system would be most appropriate.

        6. Potential Improvements: Suggest potential improvements for each system.

        7. Recommendations: Provide clear recommendations for which system to use in different scenarios.

       

        Format your comparison as a detailed academic analysis suitable for inclusion in a master's thesis,

        with appropriate headings, evidence-based conclusions, and quantitative comparisons where possible.

        """

       

        self.log("Generating comparative analysis...")

        analysis = self.query_azure_openai(

            prompt,

            system_prompt="You are an expert academic researcher specializing in document processing systems evaluation. Create a detailed, scholarly comparison suitable for a master's thesis chapter."

        )

       

        # Save the analysis

        with open(os.path.join(self.results_dir, "comparative_analysis.md"), "w", encoding="utf-8") as f:

            f.write(analysis)

           

        return analysis

   

